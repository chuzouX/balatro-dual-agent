/**
 * Normalized lookup by key or English/Chinese label
 */
const JOKER_LOOKUP_MAP = new Map<string, JokerDefinition>();

for (const def of Object.values(BALATRO_JOKERS)) {
  JOKER_LOOKUP_MAP.set(def.key.toLowerCase(), def);
  JOKER_LOOKUP_MAP.set(def.name.toLowerCase(), def);
  JOKER_LOOKUP_MAP.set(def.nameZh.toLowerCase(), def);
  // Also stripped versions
  const strippedKey = def.key.replace(/^j_/, '').replace(/_/g, ' ').toLowerCase();
  JOKER_LOOKUP_MAP.set(strippedKey, def);
  const cleanKey = def.key.replace(/^j_/, '').replace(/_/g, '').toLowerCase();
  JOKER_LOOKUP_MAP.set(cleanKey, def);
}

export function getJokerDefinition(query?: string | null): JokerDefinition | undefined {
  if (!query) return undefined;
  const q = query.trim().toLowerCase();
  const direct = JOKER_LOOKUP_MAP.get(q);
  if (direct) return direct;

  // Partial search if not found
  for (const [k, def] of JOKER_LOOKUP_MAP.entries()) {
    if (k.length > 3 && (q.includes(k) || k.includes(q))) {
      return def;
    }
  }
  return undefined;
}
