export type JokerCategory =
  | 'CHIPS'
  | 'FLAT_MULT'
  | 'XMULT'
  | 'RETRIGGER'
  | 'HAND_MODIFIER'
  | 'ECONOMY'
  | 'UTILITY'
  | 'BLUEPRINT'
  | 'BRAINSTORM';

export type JokerTriggerPhase =
  | 'played_card'   // Triggers during Played Cards phase for each scoring card
  | 'held_card'     // Triggers during Held Cards phase for each held card
  | 'joker_main'    // Triggers during Jokers phase from left to right
  | 'retrigger'     // Retriggers played or held cards
  | 'hand_modifier' // Modifies poker hand detection rules (Four Fingers, Shortcut, etc.)
  | 'passive';      // Economy or game rules (Chicot, Golden Joker, etc.)

export interface JokerDefinition {
  key: string;
  name: string;
  nameZh: string;
  rarity: 1 | 2 | 3 | 4; // 1: Common, 2: Uncommon, 3: Rare, 4: Legendary
  cost: number;
  category: JokerCategory;
  triggerPhase: JokerTriggerPhase;
  blueprintCompat: boolean;
  description: string;
  descriptionZh: string;
  baseChips?: number;
  baseMult?: number;
  baseXMult?: number;
  handType?: string;
  suit?: 'Spades' | 'Hearts' | 'Clubs' | 'Diamonds';
  faceOnly?: boolean;
  ranks?: string[];
}

